/** Which shaft each level climbs. Levels 5, 10 and 15 are the boss arenas. */
const ORDER = { 1: 'vents', 2: 'steps', 3: 'chimney', 4: 'basalt', 5: 'golem', 6: 'gallery', 7: 'throat',
  8: 'steps', 9: 'chimney', 10: 'drake', 11: 'gallery', 12: 'throat', 13: 'vents', 14: 'basalt', 15: 'throne' };
const cache = new Map();
export function shaftKey(level) { return ORDER[((level - 1) % 15) + 1]; }
export function mapFor(level) {
  const key = shaftKey(level);
  if (!cache.has(key)) cache.set(key, build(key));
  return cache.get(key);
}
function build(key) {
  const d = SHAFTS[key], m = parseMap(d.rows, d.name);
  if (d.boss) { m.boss = d.boss; m.lavaCap = d.lavaCap; }
  return m;
}
export const nameFor = (level) => SHAFTS[shaftKey(level)].name;
export const ALL_SHAFTS = () => Object.keys(SHAFTS).map(build);
