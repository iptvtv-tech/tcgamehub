const parsed = MAPS.map((d) => parseMap(d.rows, d.name, d.opts));
/** The map for a level. Levels 11–15 play the freeze levels (6–10) again, with faster guards, until section 3. */
export const mapFor = (level) => {
  const L = Math.max(1, level), n = parsed.length;
  return parsed[L <= n ? L - 1 : n - 5 + ((L - 1) % 5)];
};
export const nameFor = (level) => mapFor(level).name;
export const ALL_MAPS = () => parsed;
